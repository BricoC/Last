use serde::Deserialize;

#[derive(Deserialize)]
pub struct DdtSavePayload {
    pub(crate) id: String,
    pub(crate) doc_number: Option<i64>,
    pub(crate) year: i64,
    pub(crate) series: String,
    pub(crate) doc_date: String,
    pub(crate) status: String,
    pub(crate) is_emission: bool,
    pub(crate) updated_at: String,
    pub(crate) updated_by: String,
    pub(crate) client_id: Option<String>,
    pub(crate) client_name: String,
    pub(crate) client_address: Option<String>,
    pub(crate) client_city: Option<String>,
    pub(crate) client_vat: Option<String>,
    pub(crate) client_fiscal_code: Option<String>,
    pub(crate) client_sdi: Option<String>,
    pub(crate) client_phones_json: String,
    pub(crate) destination_name: Option<String>,
    pub(crate) destination_address: Option<String>,
    pub(crate) destination_city: Option<String>,
    pub(crate) transport_reason: String,
    pub(crate) payment_method: Option<String>,
    pub(crate) order_reference: Option<String>,
    pub(crate) account_or_balance: String,
    pub(crate) operator: Option<String>,
    pub(crate) goods_appearance: Option<String>,
    pub(crate) carriage_terms: String,
    pub(crate) packages_count: Option<String>,
    pub(crate) weight_kg: Option<String>,
    pub(crate) carrier: Option<String>,
    pub(crate) pickup_date_time: Option<String>,
    pub(crate) internal_notes: Option<String>,
    pub(crate) total_taxable_subunits: i64,
    pub(crate) total_vat_subunits: i64,
    pub(crate) total_document_subunits: i64,
    pub(crate) items: Vec<DdtItemPayload>,
}

#[derive(Deserialize)]
pub(crate) struct DdtItemPayload {
    pub(crate) id: String,
    pub(crate) row_index: i64,
    pub(crate) product_id: Option<String>,
    pub(crate) code: Option<String>,
    pub(crate) description: String,
    pub(crate) unit: String,
    pub(crate) quantity: String,
    pub(crate) unit_price_subunits: i64,
    pub(crate) discount_pct: String,
    pub(crate) net_amount_subunits: i64,
    pub(crate) vat_rate: f64,
    pub(crate) vat_amount_subunits: i64,
    pub(crate) purchase_price_subunits: i64,
}
